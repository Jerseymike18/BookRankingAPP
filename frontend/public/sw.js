/* The Reading Ledger — service worker (ONLINE-ONLY).
 *
 * This exists to make the app installable and to make a home-screen launch feel
 * instant. It is deliberately NOT an offline app.
 *
 * What it caches: build-immutable static assets only — /_next/static/* (JS, CSS,
 * the self-hosted Lora/Inter font files), the PWA icons, the manifest, the
 * favicon. Stale-while-revalidate: serve the cached copy, refresh it in the
 * background.
 *
 * What it NEVER touches — it returns without calling respondWith(), so the
 * request goes to the network exactly as if no worker were installed:
 *   - any non-GET request (every write endpoint: add-book, ratings, queue, …)
 *   - any cross-origin request (the Railway API, Supabase auth)
 *   - navigations / HTML documents — these are auth-gated per tenant and must
 *     never be served from a shared cache, and the signed-out redirect to
 *     /login must never be cached
 *   - /api/* and /data/* — live predictions, rankings and the static snapshots
 *     are data. Always the network; no stale numbers, ever.
 *
 * There is no offline fallback by design: with no network the app fails the way
 * a website fails, rather than showing a stale ledger.
 *
 * Hand-written rather than generated by next-pwa/Workbox because Next 16 builds
 * with Turbopack, where those webpack plugins never run.
 */

const VERSION = "v1";
const SHELL_CACHE = `trl-shell-${VERSION}`;

/* Small, stable, and safe to have on hand the moment the worker installs. */
const PRECACHE = [
  "/manifest.json",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/icon-512-maskable.png",
];

/** Is this a build asset we're willing to cache? Everything else falls through
 * to the network untouched. Allowlist, not denylist — a new dynamic route can
 * never accidentally become cacheable. */
function isCacheableAsset(pathname) {
  return (
    pathname.startsWith("/_next/static/") ||
    pathname.startsWith("/icons/") ||
    pathname === "/manifest.json" ||
    pathname === "/favicon.ico"
  );
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL_CACHE);
      // Individually, so one missing file can't fail the whole install.
      await Promise.all(
        PRECACHE.map((url) => cache.add(url).catch(() => undefined)),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith("trl-shell-") && key !== SHELL_CACHE)
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

/** Serve from cache, revalidate in the background. Safe here only because
 * /_next/static/* filenames are content-hashed by the build. */
async function staleWhileRevalidate(event) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(event.request);

  const refresh = fetch(event.request)
    .then((response) => {
      // `basic` == same-origin, non-opaque. Don't cache redirects or errors.
      if (response && response.status === 200 && response.type === "basic") {
        cache.put(event.request, response.clone());
      }
      return response;
    })
    .catch(() => undefined);

  if (cached) {
    event.waitUntil(refresh); // keep the worker alive for the revalidate
    return cached;
  }
  return (await refresh) || Response.error();
}

self.addEventListener("fetch", (event) => {
  const request = event.request;

  if (request.method !== "GET") return; // never intercept a write
  if (request.mode === "navigate") return; // HTML is per-tenant + auth-gated

  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }

  if (url.origin !== self.location.origin) return; // Railway API, Supabase
  if (!isCacheableAsset(url.pathname)) return; // /api, /data, everything else

  event.respondWith(staleWhileRevalidate(event));
});
